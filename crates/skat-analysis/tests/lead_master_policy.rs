#[test]
fn lead_master_policy_entire_rules_legal_deals_and_exhaustive_completions() {
    let mut next_count = 0;
    let mut terminal_count = 0;
    for c in cases() {
        let g = c.game();
        let v = g.view(c.seat);
        let k = Knowledge::from_view(&v);
        assert_eq!(baseline::rule(&v), Some(c.expected.clone()), "{}", c.id);
        assert_eq!(k.trumps_out(), c.trumps_out, "{}", c.id);
        assert_eq!(
            v.hand
                .iter()
                .filter(|&x| k.is_master(x))
                .collect::<Vec<_>>(),
            c.masters,
            "{}",
            c.id
        );
        let expected = tricks(c.next);
        let mut actual = vec![];
        fn enumerate(g: &Game, out: &mut Vec<(Seat, [Card; 3], Seat)>) {
            for a in g.legal_actions() {
                let mut h = g.clone();
                let count = h.tricks().len();
                h.apply(a).unwrap();
                if h.tricks().len() > count {
                    let t = h.tricks().last().unwrap();
                    out.push((t.leader, t.cards, t.winner));
                } else {
                    enumerate(&h, out);
                }
            }
        }
        if !expected.is_empty() {
            enumerate(&g, &mut actual);
        }
        assert_eq!(actual, expected, "{} exhaustive legal order/winners", c.id);
        // Auxiliary privacy15 has no terminal oracle and is not part of the
        // accepted3324/106 counts; original and addendum counts stay distinct.
        next_count += expected.len();
        for terminal in c.terminals {
            let mut h = g.clone();
            for (leader, cards, winner) in tricks(terminal) {
                assert_eq!(h.current_seat(), Some(leader));
                for card in cards {
                    h.apply(Action::Play(card)).unwrap();
                }
                assert_eq!(h.tricks().last().unwrap().winner, winner, "{}", c.id);
            }
            assert_eq!(h.phase(), Phase::Beendet);
            terminal_count += 1;
        }
    }
    assert_eq!(next_count, 3324);
    assert_eq!(terminal_count, 106);
}

