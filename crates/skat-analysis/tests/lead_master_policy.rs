pub(crate) fn card(n: u8) -> Card {
    Card::from_index(n).unwrap()
}
pub(crate) fn set(ns: &[u8]) -> CardSet {
    ns.iter().copied().map(card).collect()
}
pub(crate) struct Case {
    pub(crate) id: &'static str,
    pub(crate) deal: Deal,
    pub(crate) history: Vec<Action>,
    pub(crate) seat: Seat,
    pub(crate) expected: CardRule,
    pub(crate) masters: Vec<Card>,
    pub(crate) trumps_out: CardSet,
    pub(crate) next: &'static str,
    pub(crate) terminals: Vec<&'static str>,
}
impl Case {
    pub(crate) fn game(&self) -> Game {
        let mut g = Game::from_deal(self.deal, RuleConfig { kontra_re: false });
        for &a in &self.history {
            g.apply(a)
                .unwrap_or_else(|e| panic!("{} {a:?}: {e:?}", self.id));
        }
        g
    }
    #[allow(dead_code)] // Consumed by coach/app integration fixtures.
    pub(crate) fn admitted(&self) -> bool {
        self.expected.branch == Branch::LeadMaster && self.expected.winners.len() >= 2
    }
}
/// Each token is leader/card0/card1/card2/winner, from handwritten legal continuations.
pub(crate) fn tricks(s: &str) -> Vec<(Seat, [Card; 3], Seat)> {
    s.split_whitespace()
        .map(|t| {
            let v: Vec<u8> = t.split('/').map(|s| s.parse().unwrap()).collect();
            (
                Seat::from_index(v[0] as usize),
                [card(v[1]), card(v[2]), card(v[3])],
                Seat::from_index(v[4] as usize),
            )
        })
        .collect()
}
