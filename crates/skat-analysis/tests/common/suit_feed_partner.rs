impl Case {
    pub fn game(&self) -> Game {
        let mut g = Game::from_deal(self.deal, RuleConfig { kontra_re: false });
        while g.phase() == Phase::Reizen {
            let action = if g.current_seat() == Some(self.declarer) {
                if g.legal_actions().contains(&Action::Hold) {
                    Action::Hold
                } else {
                    Action::Bid(18)
                }
            } else {
                Action::Pass
            };
            g.apply(action).unwrap();
        }
        assert_eq!(g.declarer(), Some(self.declarer));
        if self.view.contract.unwrap().hand {
            g.apply(Action::Hand).unwrap();
        } else {
            g.apply(Action::TakeSkat).unwrap();
            g.apply(Action::Discard(self.deal.skat())).unwrap();
        }
        g.apply(Action::Announce(Announcement::plain(
            self.view.contract.unwrap().game,
        )))
        .unwrap();
        for c in self.history.iter().chain(&self.table) {
            g.apply(Action::Play(*c)).unwrap();
        }
        g
    }
}
