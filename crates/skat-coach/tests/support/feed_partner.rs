pub fn card(n: u8) -> Card {
    Card::from_index(n).unwrap()
}

impl Case {
    pub fn position(&self) -> Game {
        let deal = Deal::new(
            self.hands.map(|h| h.into_iter().map(card).collect()),
            self.skat.into_iter().map(card).collect(),
        )
        .unwrap();
        let mut g = Game::from_deal(
            deal,
            RuleConfig {
                kontra_re: self.kontra,
            },
        );
        for &a in self.bidding {
            g.apply(a).unwrap();
        }
        g.apply(Action::Hand).unwrap();
        let mut ann = Announcement::plain(self.game);
        ann.ouvert = self.ouvert;
        ann.schneider = self.ouvert && self.game != GameType::Null;
        ann.schwarz = ann.schneider;
        g.apply(Action::Announce(ann)).unwrap();
        for &n in self.plays {
            g.apply(Action::Play(card(n))).unwrap();
        }
        g
    }
}

