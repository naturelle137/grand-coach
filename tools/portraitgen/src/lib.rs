//! Generates the caricature portraits of the opponent figures (issue #134,
//! D-72) as SVG: one friendly bust per figure in one flat cartoon style,
//! with a heavy outline, an oversized head and a pastel disc behind it.
//! Every figure is a fixed set of [`Traits`], so each name keeps exactly
//! one portrait. Deterministic: no randomness, no network.
//!
//! The keys match `skat_app::FIGURES`; a test of `gui-egui` checks that
//! every figure has its portrait.

use std::fmt::Write;

const LICENSE: &str = "<!-- SPDX-License-Identifier: CC-BY-SA-4.0 -->";
const NOTE: &str = "<!-- Generated by tools/portraitgen (Grand-Coach); own work. -->";
/// Outline colour and width shared by every shape.
const INK: &str = "#3a2e2a";
const LINE: f32 = 2.6;
/// Centre of the face.
const CX: f32 = 100.0;
const CY: f32 = 92.0;

/// Skin tones.
#[derive(Clone, Copy)]
enum Skin {
    Light,
    Fair,
    Medium,
    Tan,
    Brown,
    Deep,
}

impl Skin {
    fn fill(self) -> &'static str {
        match self {
            Skin::Light => "#fbe3d3",
            Skin::Fair => "#f2cfb5",
            Skin::Medium => "#e0b08a",
            Skin::Tan => "#c98f63",
            Skin::Brown => "#9c6644",
            Skin::Deep => "#6f4430",
        }
    }

    fn shade(self) -> &'static str {
        match self {
            Skin::Light => "#e9c2ab",
            Skin::Fair => "#ddb093",
            Skin::Medium => "#c48f69",
            Skin::Tan => "#a9714a",
            Skin::Brown => "#7d4f33",
            Skin::Deep => "#553222",
        }
    }
}

/// Hairstyles.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Hair {
    /// Short with a soft fringe.
    Short,
    /// Short, parted on one side.
    SidePart,
    /// Very short crop.
    Crew,
    /// A raised quiff.
    Quiff,
    /// Tight curls all over.
    Curly,
    /// A round perm of small curls.
    Perm,
    /// Chin-length bob with a fringe.
    Bob,
    /// Long and parted in the middle.
    Long,
    /// Pulled back into a bun on top.
    Bun,
    /// Pulled back into a ponytail.
    Ponytail,
    /// Bald on top, tufts above the ears.
    Bald,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Glasses {
    None,
    Round,
    Square,
    /// Half-moon reading glasses low on the nose.
    Half,
    /// A monocle with its chain.
    Monocle,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Beard {
    None,
    Stubble,
    Moustache,
    /// A moustache with curled ends.
    Handlebar,
    Full,
    Goatee,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Nose {
    Button,
    Long,
    Round,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Top {
    /// Round neck.
    Sweater,
    /// Shirt collar.
    Shirt,
    /// V-neck blouse.
    Blouse,
    /// Jacket with lapels over a shirt.
    Jacket,
    /// Cardigan over a round neck.
    Cardigan,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Extra {
    Pearls,
    Earrings,
    BowTie,
    Tie,
    Freckles,
    Headband,
    FlatCap,
    Beret,
    Wrinkles,
}

/// Everything that makes one portrait.
struct Traits {
    key: &'static str,
    background: &'static str,
    skin: Skin,
    /// Half width of the head.
    width: f32,
    /// Half height of the head.
    height: f32,
    /// How far down the jaw stays wide, 0.4 (pointed) to 0.95 (square).
    jaw: f32,
    hair: Hair,
    hair_colour: &'static str,
    brows: &'static str,
    glasses: Glasses,
    beard: Beard,
    nose: Nose,
    /// Nose size factor, 1.0 normal.
    nose_size: f32,
    /// Half width of the smile.
    smile: f32,
    /// Lip colour of an open smile; `None` for a closed smile.
    lips: Option<&'static str>,
    top: Top,
    clothes: &'static str,
    extras: &'static [Extra],
}

