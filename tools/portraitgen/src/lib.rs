/// The hair over the forehead.
fn front_hair(s: &mut String, t: &Traits) {
    let c = t.hair_colour;
    let w = t.width + 3.0;
    let top = crown(t) - 4.0;
    // Fringe line height.
    let fringe = CY - t.height * 0.5;
    let dome = |s: &mut String, left_end: f32, right_end: f32, edge: &str| {
        let _ = writeln!(
            s,
            "<path d=\"M{:.1},{left_end:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{right_end:.1} {edge}Z\" fill=\"{c}\" {}/>",
            CX - w,
            CX - w,
            top - t.height * 0.35,
            CX + w,
            top - t.height * 0.35,
            CX + w,
            stroke()
        );
    };
    match t.hair {
        Hair::Short => dome(
            s,
            CY - 8.0,
            CY - 8.0,
            &format!(
                "C{:.1},{:.1} {:.1},{:.1} {CX:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1}",
                CX + w - 6.0,
                fringe - 6.0,
                CX + 20.0,
                fringe - 4.0,
                fringe + 2.0,
                CX - 20.0,
                fringe - 4.0,
                CX - w + 6.0,
                fringe - 6.0,
                CX - w,
                CY - 8.0
            ),
        ),
        Hair::SidePart => dome(
            s,
            CY - 10.0,
            CY - 10.0,
            &format!(
                "C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1} L{:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1}",
                CX + w - 4.0,
                fringe - 10.0,
                CX + 10.0,
                fringe + 8.0,
                CX - 10.0,
                fringe - 4.0,
                CX - 18.0,
                fringe - 14.0,
                CX - 26.0,
                fringe - 4.0,
                CX - w + 4.0,
                fringe - 2.0,
                CX - w,
                CY - 10.0
            ),
        ),
        Hair::Crew => dome(
            s,
            fringe - 2.0,
            fringe - 2.0,
            &format!(
                "Q{CX:.1},{:.1} {:.1},{:.1}",
                fringe - 12.0,
                CX - w,
                fringe - 2.0
            ),
        ),
        Hair::Quiff => {
            // The raised front lock first, so the dome's edge layers it.
            let _ = writeln!(
                s,
                "<path d=\"M{:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1}Z\" fill=\"{c}\" {}/>",
                CX - 30.0,
                top + 12.0,
                CX - 30.0,
                top - 16.0,
                CX + 30.0,
                top - 22.0,
                CX + 30.0,
                top - 4.0,
                CX + 16.0,
                top + 2.0,
                CX - 10.0,
                top + 6.0,
                CX - 30.0,
                top + 12.0,
                stroke()
            );
            dome(
                s,
                CY - 8.0,
                CY - 8.0,
                &format!(
                    "C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1}",
                    CX + w - 8.0,
                    fringe - 14.0,
                    CX - w + 8.0,
                    fringe - 14.0,
                    CX - w,
                    CY - 8.0
                ),
            );
        }
        Hair::Bob | Hair::Long => {
            let part = if t.hair == Hair::Long {
                format!(
                    "C{:.1},{:.1} {:.1},{:.1} {CX:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1}",
                    CX + w - 4.0,
                    fringe - 2.0,
                    CX + 10.0,
                    fringe - 16.0,
                    fringe - 18.0,
                    CX - 10.0,
                    fringe - 16.0,
                    CX - w + 4.0,
                    fringe - 2.0,
                    CX - w,
                    CY + 10.0
                )
            } else {
                format!(
                    "L{:.1},{:.1} Q{CX:.1},{:.1} {:.1},{:.1} L{:.1},{:.1}",
                    CX + w - 8.0,
                    fringe,
                    fringe + 6.0,
                    CX - w + 8.0,
                    fringe,
                    CX - w,
                    CY + 10.0
                )
            };
            dome(s, CY + 10.0, CY + 10.0, &part);
        }
        Hair::Bun | Hair::Ponytail => dome(
            s,
            CY - 6.0,
            CY - 6.0,
            &format!(
                "C{:.1},{:.1} {:.1},{:.1} {CX:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1}",
                CX + w - 2.0,
                fringe - 8.0,
                CX + 18.0,
                fringe - 12.0,
                fringe - 12.0,
                CX - 18.0,
                fringe - 12.0,
                CX - w + 2.0,
                fringe - 8.0,
                CX - w,
                CY - 6.0
            ),
        ),
        Hair::Curly | Hair::Perm => {
            // Curls along the hairline over the forehead.
            let n = 6;
            for k in 0..n {
                let x = CX - w + 10.0 + (2.0 * w - 20.0) * k as f32 / (n as f32 - 1.0);
                let lift = ((k as f32 / (n as f32 - 1.0)) - 0.5).abs() * 18.0;
                let _ = writeln!(
                    s,
                    "<circle cx=\"{x:.1}\" cy=\"{:.1}\" r=\"11\" fill=\"{c}\" {}/>",
                    fringe - 4.0 + lift,
                    stroke()
                );
            }
        }
        Hair::Bald => {
            for side in [-1.0f32, 1.0] {
                let x = CX + side * (t.width - 4.0);
                let _ = writeln!(
                    s,
                    "<path d=\"M{:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1}Z\" fill=\"{c}\" {}/>",
                    x,
                    CY - 24.0,
                    x + side * 12.0,
                    CY - 26.0,
                    x + side * 14.0,
                    CY - 6.0,
                    x + side * 6.0,
                    CY - 2.0,
                    x + side * 2.0,
                    CY - 8.0,
                    x - side * 2.0,
                    CY - 16.0,
                    x,
                    CY - 24.0,
                    stroke()
                );
            }
            // A shine on the scalp.
            let _ = writeln!(
                s,
                "<path d=\"M{:.1},{:.1} q10,-8 22,-6\" fill=\"none\" stroke=\"#ffffff\" stroke-opacity=\"0.7\" stroke-width=\"4\" stroke-linecap=\"round\"/>",
                CX - 22.0,
                crown(t) + 14.0
            );
        }
    }
}

fn face(s: &mut String, t: &Traits) {
    let ey = CY - 4.0;
    let spread = 17.0 + (t.width - 44.0) * 0.4;
    let older = t.extras.contains(&Wrinkles);
    // Cheeks.
    for side in [-1.0f32, 1.0] {
        let _ = writeln!(
            s,
            "<ellipse cx=\"{:.1}\" cy=\"{:.1}\" rx=\"9\" ry=\"6\" fill=\"#ef8a8a\" fill-opacity=\"0.35\"/>",
            CX + side * (spread + 8.0),
            ey + 20.0
        );
    }
    // Eyes and brows.
    for side in [-1.0f32, 1.0] {
        let x = CX + side * spread;
        let (rx, ry) = if older { (6.0, 6.0) } else { (7.0, 8.0) };
        let _ = writeln!(
            s,
            "<ellipse cx=\"{x:.1}\" cy=\"{ey:.1}\" rx=\"{rx:.1}\" ry=\"{ry:.1}\" fill=\"#ffffff\" {}/>",
            stroke()
        );
        let _ = writeln!(
            s,
            "<circle cx=\"{:.1}\" cy=\"{:.1}\" r=\"3.6\" fill=\"{INK}\"/>",
            x + side * -0.8,
            ey + 1.0
        );
        let _ = writeln!(
            s,
            "<circle cx=\"{:.1}\" cy=\"{:.1}\" r=\"1.2\" fill=\"#ffffff\"/>",
            x + 0.6,
            ey - 0.4
        );
        let by = ey - ry - 7.0;
        let _ = writeln!(
            s,
            "<path d=\"M{:.1},{:.1} Q{x:.1},{:.1} {:.1},{:.1}\" fill=\"none\" stroke=\"{}\" stroke-width=\"{}\" stroke-linecap=\"round\"/>",
            x - side * 9.0,
            by + 3.0,
            by - 4.0,
            x + side * 9.0,
            by + 1.0,
            t.brows,
            if older { 5.0 } else { 4.0 }
        );
        if older {
            // Laughter lines beside the eyes.
            let _ = writeln!(
                s,
                "<path d=\"M{:.1},{:.1} l{:.1},-3 M{:.1},{:.1} l{:.1},3\" fill=\"none\" stroke=\"{}\" stroke-width=\"1.8\" stroke-linecap=\"round\"/>",
                x + side * 10.0,
                ey - 1.0,
                side * 6.0,
                x + side * 10.0,
                ey + 3.0,
                side * 6.0,
                t.skin.shade()
            );
        }
    }
    nose(s, t);
    mouth(s, t);
    if t.extras.contains(&Freckles) {
        for side in [-1.0f32, 1.0] {
            for (dx, dy) in [(0.0, 0.0), (5.0, 3.0), (-4.0, 4.0), (2.0, 7.0)] {
                let _ = writeln!(
                    s,
                    "<circle cx=\"{:.1}\" cy=\"{:.1}\" r=\"1.3\" fill=\"#b0683c\" fill-opacity=\"0.8\"/>",
                    CX + side * (spread + 4.0) + dx,
                    ey + 13.0 + dy
                );
            }
        }
    }
}

