fn glasses(s: &mut String, t: &Traits) {
    let ey = CY - 4.0;
    let spread = 17.0 + (t.width - 44.0) * 0.4;
    let frame = "fill=\"#ffffff\" fill-opacity=\"0.25\"";
    match t.glasses {
        Glasses::None => {}
        Glasses::Round | Glasses::Square => {
            for side in [-1.0f32, 1.0] {
                let x = CX + side * spread;
                if t.glasses == Glasses::Round {
                    let _ = writeln!(
                        s,
                        "<circle cx=\"{x:.1}\" cy=\"{ey:.1}\" r=\"12\" {frame} {}/>",
                        stroke()
                    );
                } else {
                    let _ = writeln!(
                        s,
                        "<rect x=\"{:.1}\" y=\"{:.1}\" width=\"26\" height=\"19\" rx=\"5\" {frame} {}/>",
                        x - 13.0,
                        ey - 9.5,
                        stroke()
                    );
                }
                let _ = writeln!(
                    s,
                    "<path d=\"M{:.1},{:.1} L{:.1},{:.1}\" fill=\"none\" {}/>",
                    x + side * 12.5,
                    ey - 2.0,
                    CX + side * (t.width - 2.0),
                    ey - 5.0,
                    stroke()
                );
            }
            let _ = writeln!(
                s,
                "<path d=\"M{:.1},{:.1} Q{CX:.1},{:.1} {:.1},{:.1}\" fill=\"none\" {}/>",
                CX - spread + 12.0,
                ey - 2.0,
                ey - 7.0,
                CX + spread - 12.0,
                ey - 2.0,
                stroke()
            );
        }
        Glasses::Half => {
            let y = ey + 6.0;
            for side in [-1.0f32, 1.0] {
                let x = CX + side * spread;
                let _ = writeln!(
                    s,
                    "<path d=\"M{:.1},{y:.1} L{:.1},{y:.1} Q{x:.1},{:.1} {:.1},{y:.1}Z\" {frame} {}/>",
                    x - 12.0,
                    x + 12.0,
                    y + 18.0,
                    x - 12.0,
                    stroke()
                );
            }
            let _ = writeln!(
                s,
                "<path d=\"M{:.1},{y:.1} Q{CX:.1},{:.1} {:.1},{y:.1}\" fill=\"none\" {}/>",
                CX - spread + 12.0,
                y - 5.0,
                CX + spread - 12.0,
                stroke()
            );
        }
        Glasses::Monocle => {
            let x = CX + spread;
            let _ = writeln!(
                s,
                "<circle cx=\"{x:.1}\" cy=\"{ey:.1}\" r=\"12\" {frame} {}/>",
                stroke_w(3.2)
            );
            let _ = writeln!(
                s,
                "<path d=\"M{:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},210\" fill=\"none\" stroke=\"#c9a227\" stroke-width=\"2\"/>",
                x + 8.0,
                ey + 9.0,
                x + 22.0,
                ey + 40.0,
                x + 4.0,
                ey + 70.0,
                x + 18.0
            );
        }
    }
}

fn extras(s: &mut String, t: &Traits) {
    let neck = CY + t.height + 16.0;
    for extra in t.extras {
        match extra {
            Pearls => {
                for k in 0..9 {
                    let a = std::f32::consts::PI * (0.15 + 0.7 * k as f32 / 8.0);
                    let x = CX - 24.0 * a.cos();
                    let y = neck - 4.0 + 14.0 * a.sin();
                    let _ = writeln!(
                        s,
                        "<circle cx=\"{x:.1}\" cy=\"{y:.1}\" r=\"3.4\" fill=\"#fbf7ef\" stroke=\"{INK}\" stroke-width=\"1.4\"/>"
                    );
                }
            }
            Earrings => {
                for side in [-1.0f32, 1.0] {
                    let _ = writeln!(
                        s,
                        "<circle cx=\"{:.1}\" cy=\"{:.1}\" r=\"4\" fill=\"#e8c547\" stroke=\"{INK}\" stroke-width=\"1.6\"/>",
                        CX + side * (t.width - 2.0),
                        CY + 18.0
                    );
                }
            }
            BowTie => {
                let y = neck + 6.0;
                let _ = writeln!(
                    s,
                    "<path d=\"M{CX:.1},{y:.1} L{:.1},{:.1} L{:.1},{:.1}Z M{CX:.1},{y:.1} L{:.1},{:.1} L{:.1},{:.1}Z\" fill=\"#b8313a\" {}/>",
                    CX - 16.0,
                    y - 9.0,
                    CX - 16.0,
                    y + 9.0,
                    CX + 16.0,
                    y - 9.0,
                    CX + 16.0,
                    y + 9.0,
                    stroke()
                );
                let _ = writeln!(
                    s,
                    "<circle cx=\"{CX:.1}\" cy=\"{y:.1}\" r=\"4\" fill=\"#b8313a\" {}/>",
                    stroke()
                );
            }
            Tie => {
                let y = neck + 8.0;
                let _ = writeln!(
                    s,
                    "<path d=\"M{:.1},{y:.1} L{:.1},{y:.1} L{:.1},{:.1} L{CX:.1},210 L{:.1},{:.1}Z\" fill=\"#c0392b\" {}/>",
                    CX - 5.0,
                    CX + 5.0,
                    CX + 8.0,
                    y + 40.0,
                    CX - 8.0,
                    y + 40.0,
                    stroke()
                );
            }
            Headband => {
                let y = CY - t.height * 0.5 - 14.0;
                let _ = writeln!(
                    s,
                    "<path d=\"M{:.1},{:.1} Q{CX:.1},{:.1} {:.1},{:.1}\" fill=\"none\" stroke=\"#e26d5a\" stroke-width=\"8\" stroke-linecap=\"round\"/>",
                    CX - t.width,
                    y + 12.0,
                    y - 20.0,
                    CX + t.width,
                    y + 12.0
                );
            }
            FlatCap => {
                let top = crown(t) - 8.0;
                let _ = writeln!(
                    s,
                    "<path d=\"M{:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1} C{:.1},{:.1} {:.1},{:.1} {:.1},{:.1}Z\" fill=\"#6e6253\" {}/>",
                    CX - t.width - 6.0,
                    top + 26.0,
                    CX - t.width,
                    top - 12.0,
                    CX + t.width + 8.0,
                    top - 14.0,
                    CX + t.width + 20.0,
                    top + 22.0,
                    CX + 20.0,
                    top + 30.0,
                    CX - 10.0,
                    top + 30.0,
                    CX - t.width - 6.0,
                    top + 26.0,
                    stroke()
                );
            }
            Beret => {
                let top = crown(t) - 10.0;
                let _ = writeln!(
                    s,
                    "<ellipse cx=\"{:.1}\" cy=\"{:.1}\" rx=\"{:.1}\" ry=\"16\" fill=\"#a3333d\" {}/>",
                    CX - 6.0,
                    top + 10.0,
                    t.width + 8.0,
                    stroke()
                );
                let _ = writeln!(
                    s,
                    "<path d=\"M{:.1},{:.1} l3,-8\" fill=\"none\" {}/>",
                    CX - 2.0,
                    top - 5.0,
                    stroke()
                );
            }
            Freckles | Wrinkles => {}
        }
    }
}

